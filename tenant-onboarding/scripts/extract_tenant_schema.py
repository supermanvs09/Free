#!/usr/bin/env python3
"""Rebuilds sql/tenant_schema.sql and sql/tenant_seed.sql from a pg_dump of nhi_db.

    scripts/extract_tenant_schema.py nhi_db.sql source_schema [out_dir]

It keeps the structure of one tenant schema (the one you name) and nothing
else: no rows, no sequence positions, no owners, no fixed partitions. The
schema name becomes __SCHEMA__; the provisioner fills it in and creates the
time partitions itself (they depend on today's date).
"""
import re, sys

src = sys.argv[1]
schema = sys.argv[2]
out_dir = sys.argv[3] if len(sys.argv) > 3 else "sql"
# Small configuration tables the ISPM and drift engines read; copied with
# their rows so a new tenant scores out of the box. Everything else starts empty.
SEED_TABLES = ["ispm_pillars", "ispm_categories", "ispm_rule_weights", "drift_config"]
KEEP = {"FUNCTION", "TABLE", "SEQUENCE", "SEQUENCE OWNED BY", "DEFAULT", "CONSTRAINT",
        "INDEX", "FK CONSTRAINT", "TRIGGER", "COMMENT", "VIEW"}
# Partition children (and their indexes) are created per tenant at run time.
CHILD = re.compile(r"^ispm_identity_posture_(daily|hourly)_(\d|default)")
PARENT = r"ispm_identity_posture_(?:daily|hourly)"

text = open(src, encoding="utf-8").read().split("\n")
head = re.compile(r"^-- Name: (.*); Type: ([A-Z ]+); Schema: ([^;]+); Owner: ")
blocks, cur = [], None
for i, line in enumerate(text):
    m = head.match(line)
    if m:
        cur = {"name": m.group(1), "type": m.group(2), "schema": m.group(3), "body": []}
        blocks.append(cur)
        continue
    if line.startswith("-- Data for Name:"):
        cur = None
        continue
    if cur is not None:
        cur["body"].append(line)

out = []
for b in blocks:
    if b["schema"] != schema or b["type"] not in KEEP:
        continue
    first = b["name"].split(" ")[0].split(".")[0]
    if CHILD.match(first) or CHILD.match(b["name"].split(" ")[-1]):
        continue
    body = "\n".join(b["body"])
    # drop the trailing "--" comment framing and OWNER statements
    body = re.sub(r"^ALTER (TABLE|SEQUENCE|FUNCTION|VIEW)[^\n]* OWNER TO [^\n]*\n", "", body, flags=re.M)
    body = re.sub(r"\n--\s*$", "", body.strip("\n") + "\n").strip("\n")
    body = re.sub(r"(?m)^--.*\n?", "", body).strip("\n")
    if not body:
        continue
    # Every mention, including the tenant name inside index and constraint names
    # (uq_<tenant>_credentials_arn_account): the scanner may refer to those.
    body = body.replace(schema, "__SCHEMA__")
    # In nhi_db two keys of the source tenant point into the shared nhi_scanner
    # schema (a table of one tenant must not depend on another schema's rows).
    # A new tenant's keys point at its own identities and credentials.
    body = body.replace("REFERENCES nhi_scanner.", "REFERENCES __SCHEMA__.")
    # Constraints and indexes on the partitioned parents: no ONLY, so they
    # propagate to the partitions created afterwards.
    body = re.sub(r"ALTER TABLE ONLY (__SCHEMA__\." + PARENT + r")\b", r"ALTER TABLE \1", body)
    body = re.sub(r"ON ONLY (__SCHEMA__\." + PARENT + r")\b", r"ON \1", body)
    out.append(f"-- {b['type']}: {b['name'].replace(schema, '__SCHEMA__')}\n{body}\n")

header = (
    "-- {what}, generated by scripts/extract_tenant_schema.py\n"
    "-- from a reference tenant schema of nhi_db. __SCHEMA__ is replaced by the tenant's db_name.\n"
    "-- Do not edit by hand: change the source schema and regenerate.\n\n"
)
with open(out_dir + "/tenant_schema.sql", "w", encoding="utf-8") as f:
    f.write(header.format(what="Structure of one NHI tenant schema") + "\n".join(out))


def unescape(v):
    if v == "\\N":
        return None
    esc = {"\\": "\\", "t": "\t", "n": "\n", "r": "\r", "b": "\b", "f": "\f", "v": "\v"}
    return re.sub(r"\\(.)", lambda m: esc.get(m.group(1), m.group(1)), v)


def lit(v):
    return "NULL" if v is None else "'" + v.replace("'", "''") + "'"


seed_by_table, i = {}, 0
while i < len(text):
    m = re.match(r"^COPY " + re.escape(schema) + r"\.(\w+) \((.*)\) FROM stdin;$", text[i])
    if m and m.group(1) in SEED_TABLES:
        table, cols = m.group(1), m.group(2)
        i += 1
        rows = []
        while text[i] != "\\.":
            rows.append("(" + ", ".join(lit(unescape(v)) for v in text[i].split("\t")) + ")")
            i += 1
        if rows:
            seed_by_table[table] = (f"INSERT INTO __SCHEMA__.{table} ({cols}) VALUES\n  " + ",\n  ".join(rows) + "\nON CONFLICT DO NOTHING;\n")
    i += 1
# SEED_TABLES is in foreign-key order (pillars before categories before rules).
seed = [seed_by_table[t] for t in SEED_TABLES if t in seed_by_table]
with open(out_dir + "/tenant_seed.sql", "w", encoding="utf-8") as f:
    f.write(header.format(what="Reference rows every new tenant schema starts with") + "\n".join(seed))
