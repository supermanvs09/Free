// Writes the Content-Security-Policy that nginx sends (see nginx/), from the built site:
// - inline <script>s run only if their exact SHA-256 hash is listed (every one in dist/ is);
// - the lead forms may post only to their endpoint (SITE.formEndpoint in src/data/site.js);
// - the language menu may load Google's page translator and nothing else from outside.
//   node scripts/csp.mjs [out-file]      (default: csp.conf, after `npm run build`)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = process.argv[2] || join(root, 'csp.conf');

const pages = [];
const walk = (dir) => readdirSync(dir, { withFileTypes: true }).forEach((e) => {
  const p = join(dir, e.name);
  if (e.isDirectory()) walk(p); else if (e.name.endsWith('.html')) pages.push(p);
});
walk(join(root, 'dist'));
if (!pages.length) throw new Error('dist/ has no pages: run npm run build first');

const hashes = new Set();
for (const page of pages) {
  for (const [, attrs, body] of readFileSync(page, 'utf8').matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/type=["']?application\/ld\+json/.test(attrs)) continue; // data, never executed
    hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
  }
}

const { SITE } = await import(pathToFileURL(join(root, 'src/data/site.js')).href);
const endpoint = new URL(SITE.formEndpoint).origin;
// Google's page translator, loaded only when a visitor picks a language other than English
const GT = 'https://translate.google.com https://translate.googleapis.com https://translate-pa.googleapis.com https://www.gstatic.com https://www.google.com';

const policy = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')} ${GT}`,
  `style-src 'self' 'unsafe-inline' ${GT}`, // React writes style attributes for layout and animation
  `img-src 'self' data: ${GT}`,
  "font-src 'self' data:", // Vite inlines the smallest font subsets as data: URIs
  "media-src 'self'",
  `connect-src 'self' ${endpoint} ${GT}`,
  "manifest-src 'self'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

writeFileSync(out, `# Generated by scripts/csp.mjs from the built pages. Do not edit by hand.\nadd_header Content-Security-Policy "${policy}" always;\n`);
console.log(`CSP: ${hashes.size} inline script hash(es), forms -> ${endpoint} -> ${out}`);
