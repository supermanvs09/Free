const wrap = (Icon, weight = 'regular') => {
  const C = forwardRef(function Icon_({ strokeWidth: _s, size, ...rest }, ref) {
    return createElement(Icon, { ref, weight, size: size ?? '1em', ...rest });
  });
  return C;
};
