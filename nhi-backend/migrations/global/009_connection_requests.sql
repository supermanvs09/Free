-- Safe to run again. Also applied by the API at start (internal/platform/globalschema).
--
-- One row each time somebody clicks "Verify connection" on the Integrations
-- page: who, for which customer AWS account and role, in which regions. It is
-- written BEFORE any check runs, and the platform admins are e-mailed at that
-- moment (the row records how that went). When the checks have finished the
-- row gets their outcome.
--
-- Not the approvals table: nhi_global.connection_approvals holds one decision
-- per account that passed its checks and is what the onboarding tool's
-- Approvals page lists. A click that fails its checks never reaches it, but it
-- is still recorded here.
BEGIN;

CREATE TABLE IF NOT EXISTS nhi_global.connection_requests (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             uuid        NOT NULL,
    db_name               text        NOT NULL DEFAULT '',
    tenant_domain         text        NOT NULL DEFAULT '',
    client_aws_account_id text        NOT NULL,                 -- the customer's AWS account
    role_arn              text        NOT NULL DEFAULT '',
    regions               text[]      NOT NULL DEFAULT '{}',
    requested_by          text        NOT NULL DEFAULT '',
    requested_at          timestamptz NOT NULL DEFAULT now(),
    request_id            text        NOT NULL DEFAULT '',      -- the API request, to find it in the logs
    -- started | failed | pending_approval | watching_events | connected | refused | error
    outcome               text        NOT NULL DEFAULT 'started',
    outcome_detail        text        NOT NULL DEFAULT '',
    checks                jsonb       NOT NULL DEFAULT '[]'::jsonb,
    finished_at           timestamptz,
    -- The e-mail to the platform admins: sent | failed | not_configured | suppressed
    email_status          text        NOT NULL DEFAULT '',
    email_error           text        NOT NULL DEFAULT '',
    emailed_at            timestamptz
);

CREATE INDEX IF NOT EXISTS connection_requests_tenant_time
    ON nhi_global.connection_requests (tenant_id, requested_at DESC);
CREATE INDEX IF NOT EXISTS connection_requests_account_time
    ON nhi_global.connection_requests (client_aws_account_id, requested_at DESC);

COMMIT;
