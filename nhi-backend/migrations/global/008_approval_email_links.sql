-- One-time links in the "approval needed" e-mail, so an approver can approve or
-- reject from the e-mail itself. Safe to run again.
--
-- One row per recipient and request. The token in the link is a random 256-bit
-- value that is never stored: only its SHA-256 is. A link works once, until it
-- expires, and only while its request is still pending. Whoever decides is
-- recorded as the e-mail address the link was sent to.
BEGIN;
CREATE TABLE IF NOT EXISTS nhi_global.connection_approval_links (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id  bigint      NOT NULL REFERENCES nhi_global.connection_approvals (id) ON DELETE CASCADE,
    email        text        NOT NULL,
    token_hash   text        NOT NULL UNIQUE,   -- hex SHA-256 of the token
    expires_at   timestamptz NOT NULL,
    used_at      timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS connection_approval_links_approval ON nhi_global.connection_approval_links (approval_id);
COMMIT;
