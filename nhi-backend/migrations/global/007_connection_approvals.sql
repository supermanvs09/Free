-- Apply once to nhi_db, after 001-006. Safe to run again.
--
-- An AWS account that has passed every connection check waits here for a
-- platform super admin to approve it (the tenant-onboarding service's
-- Approvals page). One row per request; at most one pending request per
-- tenant and account. The tenant's own accounts row carries the outcome in
-- its approval_* columns (migrations/tenant/009_account_approval.sql).
BEGIN;

CREATE TABLE IF NOT EXISTS nhi_global.connection_approvals (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid        NOT NULL,
    db_name            text        NOT NULL,
    tenant_domain      text        NOT NULL DEFAULT '',
    account_id         text        NOT NULL,
    role_arn           text        NOT NULL DEFAULT '',
    regions            text[]      NOT NULL DEFAULT '{}',
    checks             jsonb       NOT NULL DEFAULT '[]'::jsonb,
    events             jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- regions seen, messages scanned, how long it took
    requested_by       text        NOT NULL DEFAULT '',
    requested_at       timestamptz NOT NULL DEFAULT now(),
    status             text        NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn')),
    decided_by         text,
    decided_at         timestamptz,
    decision_note      text        NOT NULL DEFAULT '',
    -- The e-mail to the approvers: sent | failed | not_configured.
    email_status       text        NOT NULL DEFAULT '',
    email_error        text        NOT NULL DEFAULT '',
    emailed_at         timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS connection_approvals_one_pending
    ON nhi_global.connection_approvals (tenant_id, account_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS connection_approvals_status_time
    ON nhi_global.connection_approvals (status, requested_at DESC);

COMMIT;
